import { useState } from "react";
import ReviewForm from "./ReviewForm";

export default function ParagraphAnalysis({ record }) {
  const [result, setResult] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  async function handleAnalyse() {
    if (loading) return;

    setLoading(true);
    setError("");
    setResult(null);

    try {
      const response = await fetch("/analyse", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          source_file: record.source_file,
          paragraph_number: record.paragraph_number,
        }),
      });

      const data = await response.json();

      if (!response.ok) {
        throw new Error(
          typeof data.detail === "string"
            ? data.detail
            : "Analysis failed. Please try again."
        );
      }

      setResult(data);
    } catch (error) {
      setError(error.message || "Could not reach the analysis service.");
    } finally {
      setLoading(false);
    }
  }

  return (
    <section aria-label="Verb analysis">
      <button
        type="button"
        onClick={handleAnalyse}
        disabled={loading}
      >
        {loading ? "Analysing…" : "Analyse verb forms"}
      </button>

      {loading && <p role="status">Waiting for the local model…</p>}
      {error && <p role="alert">{error}</p>}

      {result && (
        <div>
          <h3>Suggested verb analyses</h3>

          <p>
            Generated by {result.model}. Please review the grammatical
            labels and explanations.
          </p>

          {result.quotations_verified && (
            <p>
              Quotations checked against the source, ignoring whitespace
              differences.
            </p>
          )}

          {result.analysis.length === 0 ? (
            <p>The model returned no verb examples.</p>
          ) : (
            <ol>
              {result.analysis.map((example, index) => (
                <li key={index}>
                  <p>
                    <strong>{example.verb_form}</strong>
                    {" — "}
                    {example.construction}
                  </p>

                  <blockquote>{example.quotation}</blockquote>
                  <p>{example.explanation}</p>

                  <ReviewForm
                    record={record}
                    example={example}
                    modelName={result.model}
                  />
                </li>
              ))}
            </ol>
          )}
        </div>
      )}
    </section>
  );
}